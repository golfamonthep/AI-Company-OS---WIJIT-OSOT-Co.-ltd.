import { Toaster } from "@/components/ui/sonner";
import { TooltipProvider } from "@/components/ui/tooltip";
import NotFound from "@/pages/NotFound";
import { Route, Switch } from "wouter";
import ErrorBoundary from "./components/ErrorBoundary";
import { ThemeProvider } from "./contexts/ThemeContext";
import Home from "./pages/Home";
import AdAnalyzer from "./pages/AdAnalyzer";
import AdCopyGenerator from "./pages/AdCopyGenerator";
import HealthCheck from "./pages/HealthCheck";
import Dashboard from "./pages/Dashboard";
import BudgetMonitor from "./pages/BudgetMonitor";

function Router() {
  // make sure to consider if you need authentication for certain routes
  return (
    <Switch>
      <Route path={"/"} component={Home} />
      <Route path={"/analyzer"} component={AdAnalyzer} />
      <Route path={"/copy-generator"} component={AdCopyGenerator} />
      <Route path={"/health-check"} component={HealthCheck} />
      <Route path={"/dashboard"} component={Dashboard} />
      <Route path={"/budget-monitor"} component={BudgetMonitor} />
      <Route path={"/404"} component={NotFound} />
      {/* Final fallback route */}
      <Route component={NotFound} />
    </Switch>
  );
}

// NOTE: About Theme
// - First choose a default theme according to your design style (dark or light bg), than change color palette in index.css
//   to keep consistent foreground/background color across components
// - If you want to make theme switchable, pass `switchable` ThemeProvider and use `useTheme` hook

function App() {
  return (
    <ErrorBoundary>
      <ThemeProvider
        defaultTheme="light"
        // switchable
      >
        <TooltipProvider>
          <Toaster />
          <Router />
        </TooltipProvider>
      </ThemeProvider>
    </ErrorBoundary>
  );
}

export default App;
